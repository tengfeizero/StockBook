package service

// 演示数据「行业模板」——只放场景数据，生成流程统一由 demo.go 执行。
// 新增一个行业：在本文件加一份 demoProfile 并登记到 demoProfiles 即可，
// 不需要改动清库/建账/开单/收付款逻辑。
//
// 约定：
//   - 成本/价格单位一律「分」，数量一律 ×1000（与业务表一致）
//   - 库位容量与占用同量纲（qty 件 / volume 升×1000 / weight kg×1000）
//   - 启用批次（batch=true）的商品在期初/采购入库会自动带批次号
//   - 只有登记了体积/重量的商品才在对应计量方式的货架上计占用（否则 unknown_skus 提示）

// demoLoc 演示货架
type demoLoc struct {
	Code, Name, Remark, Mode string
	Capacity, MinQty         int64
}

// demoCat 分类，loc = 该分类默认货架在 Locations 中的下标
type demoCat struct {
	Name string
	Loc  int
}

// demoProduct 演示商品
// 字段顺序：编码 条码 名称 单位 分类 成本(分) 采购批量 安全库存 期初数量
//
//	PLU 批次 保质期(天) 单件体积(升×1000) 单件重量(kg×1000)
type demoProduct struct {
	Code, Barcode, Name, Unit string
	Cat                       int
	Cost, Pack, Safe, Opening int64
	PLU                       string
	Batch                     bool
	ShelfDays                 int
	Volume, Weight            int64
}

// demoPartner 供应商/客户；Wholesale=true 表示该客户走批发价（模板没有批发价时退会员价）
type demoPartner struct {
	Code, Name, Contact, Phone, Addr string
	Opening                          int64
	Wholesale                        bool
}

// demoPriceTier 价位；Pct=成本百分比，Jitter=默认价位再叠加 0~Jitter% 的随机浮动
type demoPriceTier struct {
	Name   string
	Pct    int
	Jitter int
}

// demoProfile 一个行业演示模板
type demoProfile struct {
	Key    string
	Name   string
	Scene  string // 一句话场景说明（前端展示）
	Detail string // 档案/业务数据概况（前端展示）
	Seed   int64  // 固定种子：同一模板每次生成的数据一致

	ShopName, ShopPhone, ShopAddr, TicketFooter string

	Locations  []demoLoc
	Cats       []demoCat
	Products   []demoProduct
	PriceTiers []demoPriceTier

	Suppliers []demoPartner
	Customers []demoPartner

	PurchaseDocs   int
	SalesDocs      int
	StocktakeItems int
	SpanDays       int // 单据日期跨度（天）

	BatchPrefix string // 批次号前缀
	BatchDaily  bool   // true=按日批次（生鲜），false=按月批次

	Quotations          []string
	PurchaseOrderRemark string
	OtherInRemark       string
	OtherOutRemark      string
}

